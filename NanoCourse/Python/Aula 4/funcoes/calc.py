#funcao de soma
def somar(a, b):
    return float(a) + float(b)

#funcao de subtracao
def subtrair(a, b):
    return float(a) - float(b)

#funcao de divisao
def divisao(a, b):
    if b == 0:
        return 0
    return float(a) / float(b)

#funcao de multiplicacao
def multiplicar(a, b):
    return float(a) * float(b)