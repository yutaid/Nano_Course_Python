#Pedir a distancia da viagem
d = float(input("Porfavor, digite a distancia: "))

#Pedir o tempo da viagem

t = float(input("Porfavor, digite o tempo: "))

#Dividir a distancia pelo tempo

Velocidade_Média = d / t

#Exibir o resultado para o usuario

print(f"A velocidadé média é de {Velocidade_Média:.2f} km/h")